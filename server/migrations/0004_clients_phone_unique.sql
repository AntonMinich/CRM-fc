-- 0004_clients_phone_unique.sql
-- Телефон уникален среди клиентов: сравнение идёт по значению колонки phone,
-- которое сервер хранит нормализованным (+375XXXXXXXXX).
--
-- fincode: tolerate-existing-data
-- Если в таблице уже есть дубли телефонов, индекс не создаётся: данные не
-- удаляются и не изменяются, миграция не отмечается применённой и повторится
-- при следующем запуске. Проверку дубля в этом случае выполняет сервер.

CREATE UNIQUE INDEX IF NOT EXISTS idx_clients_phone_unique ON clients (phone);
