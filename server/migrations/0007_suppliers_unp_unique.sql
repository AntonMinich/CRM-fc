-- 0007_suppliers_unp_unique.sql
-- УНП уникален среди поставщиков.
--
-- fincode: tolerate-existing-data
-- Если в таблице уже есть дубли УНП, индекс не создаётся: данные не удаляются и
-- не изменяются, миграция не отмечается применённой и повторится при следующем
-- запуске. Проверку дубля в этом случае выполняет сервер.
--
-- Уникального индекса по телефону быть не должно: дубль телефона не блокирует
-- сохранение. Если индекс успел примениться раньше, он удаляется.

DROP INDEX IF EXISTS idx_suppliers_phone_unique;

CREATE UNIQUE INDEX IF NOT EXISTS idx_suppliers_unp_unique ON suppliers (unp);
